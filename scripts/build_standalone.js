/**
 * Builds Pitwall.html: a single self-contained file that runs by simply
 * double-clicking it, with no server, install or internet connection.
 *
 * Browsers block ES modules and fetch() for pages opened from disk (file://),
 * so this script inlines everything the app needs into one HTML page:
 * the stylesheet, Chart.js, the logo, the dataset and the app code
 * (analytics.js + app.js converted from modules into one plain script).
 *
 * Run after changing anything in docs/:  npm run standalone
 */
import { readFile, writeFile } from "node:fs/promises";

const docs = new URL("../docs/", import.meta.url);
const read = (name) => readFile(new URL(name, docs), "utf8");
const output = new URL("../Pitwall.html", import.meta.url);

// The monthly explorer needs a web server, so link to the hosted copy instead.
const MONTHLY_URL =
  "https://nolimitbaiza.github.io/f1_constructor_performance_tracker/monthly.html";

/** Replaces exactly one occurrence of `search`, failing loudly if it is missing. */
function replaceOnce(text, search, replacement) {
  const count = text.split(search).length - 1;
  if (count !== 1)
    throw new Error(`Expected one match for ${search}, found ${count}`);
  return text.replace(search, () => replacement);
}

/** Prevents inlined code from closing the surrounding <script> tag early. */
const safeScript = (code) => code.replaceAll("</script", "<\\/script");

const [html, css, chart, analytics, app, logo, json] = await Promise.all(
  [
    "index.html",
    "app.css",
    "vendor/chart.umd.js",
    "analytics.js",
    "app.js",
    "logo.svg",
    "data.json",
  ].map(read),
);

// Turn the two ES modules into one plain script: drop `export` keywords and
// the import statement (both files end up in the same scope instead).
const analyticsCode = analytics.replace(/^export /gm, "");
const appCode = app.replace(
  /^import \{[^}]*\} from "\.\/analytics\.js";\n/m,
  "",
);
if (appCode === app) throw new Error("Could not find the analytics import");

// "<" is escaped so the data can never be read as HTML.
const data = JSON.stringify(JSON.parse(json)).replaceAll("<", "\\u003c");
const logoUri = `data:image/svg+xml;base64,${Buffer.from(logo).toString("base64")}`;

let page = html;
page = replaceOnce(
  page,
  '<link rel="icon" href="logo.svg" type="image/svg+xml" />',
  `<link rel="icon" href="${logoUri}" type="image/svg+xml" />`,
);
page = replaceOnce(page, 'src="logo.svg"', `src="${logoUri}"`);
page = replaceOnce(
  page,
  '<link rel="stylesheet" href="app.css" />',
  `<style>\n${css}</style>`,
);
page = replaceOnce(
  page,
  '<script src="vendor/chart.umd.js" defer></script>',
  "",
);
page = replaceOnce(page, '<script type="module" src="app.js"></script>', "");
page = replaceOnce(
  page,
  'href="monthly.html"',
  `href="${MONTHLY_URL}" target="_blank" rel="noopener"`,
);

// Scripts go at the end of <body> so the page elements exist when they run.
const scripts = [
  "<!-- Chart.js (MIT licence, see docs/vendor/chart.LICENSE.md) -->",
  `<script>\n${safeScript(chart)}\n</script>`,
  "<!-- Race dataset (generated from data/raw by scripts/build_app_data.py) -->",
  `<script>window.PITWALL_DATA = ${data};</script>`,
  "<!-- Pitwall app: docs/analytics.js + docs/app.js -->",
  `<script>\n(() => {\n${safeScript(analyticsCode)}\n${safeScript(appCode)}\n})();\n</script>`,
].join("\n");
page = replaceOnce(page, "</body>", `${scripts}\n</body>`);

const banner =
  "<!-- Generated by scripts/build_standalone.js — edit the files in docs/ and run `npm run standalone` instead of editing this file. -->\n";
page = replaceOnce(page, "<!doctype html>\n", `<!doctype html>\n${banner}`);
await writeFile(output, page);
console.log(
  `Wrote Pitwall.html (${(Buffer.byteLength(page) / 1e6).toFixed(1)} MB)`,
);
